/**
 * 感想戦の部屋 (v1.50・親 §9.4／§6.3.6・画面機能 §3 S04／S11・付録D-12 §8)。
 *
 * **部屋を建てるのは通信機能 (features/matchmaking)、押すのは感想戦の画面
 * (features/kifu-replay)** で、どちらも features なので直接は行き来しない。
 * registry の口を通すため、**やり取りする形だけをここ (core) に置く**。
 *
 * 通信機能を積んでいないビルド (アプリ A) では口ごと無い＝**ボタンも出ない**。
 */

/** 部屋を建てられない理由。**「押せない」だけでは待てば直るのかが分からない**ので、理由で返す。 */
export type ReviewRoomBlock =
  /** 建てられる。 */
  | 'ok'
  /** サーバーにつながっていない（通信機能そのものが無い場合を含む）。 */
  | 'no-server'
  /** 既にどこかの部屋に居る＝そこを使えばよいので、新しく建てる意味が無い。 */
  | 'already-in-room';

/**
 * ★v1.54: 感想戦ロビー (S12) が、部屋を建てる前に棋譜から取る情報（親 v1.48 §9.4.1）。
 *
 * **ロビーは通信機能の側に居て棋譜を知らない**ので、既定の部屋名に使うルール名まで
 * 含めてこちらへ渡す。**記憶が空でも建てられる**（中で読み込めるため）＝そのときは
 * ルール名だけが空になる。
 */
export interface ReviewRoomInfo {
  gameType: 'shogi' | 'hasami' | 'shogi-custom';
  torus: boolean;
  quantum: boolean;
  customRuleName?: string;
  /** 既定の部屋名に使う、いま記憶している 1 局のルール名（空＝記憶が無い）。 */
  ruleName: string;
}

/** 感想戦の部屋を建てるのに要る、棋譜から取れるだけの情報。 */
export interface ReviewRoomRequest {
  gameType: 'shogi' | 'hasami' | 'shogi-custom';
  torus: boolean;
  quantum: boolean;
  customRuleName?: string;
  /** 部屋名。**既定は棋譜のルール名＋「の感想戦」**だが、決め直せる（付録D-12 §8）。 */
  roomName: string;
  /**
   * v1.52: 一覧に出る自分の名前。**決めてもらったものを使う**＝v1.51 は前に使った
   * 名前の流用しか無く、ロビーを通っていない人は**空のまま建っていた**。
   */
  playerName: string;
  /**
   * ★v1.55: 合言葉（親 v1.49 §9.4.4）。**S04 とまったく同じ扱い**にする。
   * 省略＝合言葉なし。**終局から移ってくる部屋は、ここへその場限りの合言葉が入る**
   * （§6.3.6 の移る手順＝名前だけで見分けず、最後は合言葉が決める）。
   */
  password?: string;
  /** ★v1.55: 一覧に出すか。省略＝出す。**移ってきた部屋は必ず非公開**（§9.4.4）。 */
  isPublic?: boolean;
  /**
   * ★v1.55: 観戦を許すか（親 §6.8.2／§6.8.6）。省略＝許す。
   *
   * **感想戦ロビーから建てた部屋は、対局の部屋とまったく同じ扱いで観戦できる**。
   * **終局から移ってきた部屋は非公開＋人に見せない合言葉**なので、許していても
   * 外から新しい観戦者は入って来られない（連れて移った人だけが入る）。
   */
  allowSpectators?: boolean;
}
