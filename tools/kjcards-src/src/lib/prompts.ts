import type { Board } from '../types';
import { serializeBoard } from './serialize';

/** §7.3: カード化依頼プロンプト（入口） */
export function buildCardRequestPrompt(sourceText: string): string {
  const body = sourceText.trim();
  return [
    '以下の文章を、KJ法のカードに分解してください。ルール:',
    '- 1カード＝1トピックに原子化する。',
    '- 同じ意味の重複はまとめる。書かれていない情報を推測で足さない。',
    '- 1行につき1カード。各行は「見出し ｜ 補足」の形。補足が無ければ「見出し」だけでよい。',
    '- 記号や括弧で囲わず、上記の行だけを並べて返す（前後の説明文は不要）。',
    '---',
    '【対象の文章】',
    body || '（ここに取り留めのない文章を貼ってください）',
  ].join('\n');
}

/** §8.3: 受け渡しプロンプト（出口）＝直列化した素材＋指示文 */
export function buildHandoffPrompt(board: Board): string {
  const material = serializeBoard(board);
  const instruction = [
    '',
    '――――――――――',
    '上記は、ある文章のための素材（グループ・カード・関係）と目的です。次をお願いします。',
    '1. 目的に沿って、語る順番（一列の構成）を2〜3案提案してください。各案に短い理由を付けてください。',
    '2. 私が引いたグループ分けと関係線を尊重し、勝手に再編・削除・創作をしないでください。足りない点は"提案"として別に伝えてください。',
    '3. 各案は、順序つきのアウトライン（案の狙い→番号付きでグループと中身→短い理由）で示してください。',
    '4. 私が「これを前に」「入れ替えて」等と返したら、その指示どおりに順番を更新し、アウトラインを出し直してください。',
    '5. 順番が固まったら、私が「文章化して」と言ったときにだけ、その順番どおりに清書してください。',
    '   ・合意した順番・構成に忠実に書き、順序や構成を勝手に変えない。',
    '   ・各グループを表札に対応する段落／節にする。',
    '   ・カードの見出し／補足を材料に自然な文へ膨らませ、書かれていない事実を創作しない。',
    '   ・関係ラベル（だから→そのため、でも→一方で、なぜなら→なぜなら 等）に応じた接続でつなぐ。',
    '   ・目的の「読み手」「調子」を反映する。',
  ].join('\n');
  return material + '\n' + instruction;
}

/** フェイルソフト用: 取り込めなかったAI出力を直させる再依頼文（§7.5） */
export function buildFixImportPrompt(): string {
  return [
    'さきほどのカード一覧が、指定した形式になっていませんでした。次の形式で出し直してください。',
    '- 1行につき1カード。各行は「見出し ｜ 補足」の形（補足が無ければ見出しだけ）。',
    '- 記号や括弧で囲わない。前後の説明文は付けない。上記の行だけを並べて返す。',
  ].join('\n');
}
